// Publish one rotated public campaign from its GitHub Release.
// The weekly Remotion publisher keeps its own promo-ep-N namespace and schedule.
import fs from "node:fs";
import path from "node:path";
import { execFileSync, spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { arg, loadProjects, projectLanguage, site } from "./common.mjs";
import { buildCampaign } from "./copy.mjs";

const repo = process.env.GITHUB_REPOSITORY || "jonsnow-org/Ttbik";
const root = process.cwd();
const output = arg("out", "promo-out");
const id = arg("id", "");
const tag = arg("tag", "");
const format = arg("format", "vertical");
const project = loadProjects().find((item) => item.id === id);
const fail = (message) => { throw new Error(message); };
if (!project) fail(`unknown campaign id: ${id}`);
if (!/^promo-campaign-[a-z0-9-]+-\d{8}$/.test(tag)) fail("invalid campaign release tag");
if (format !== "vertical") fail("automatic social publishing requires a vertical video");
const asset = `${id}-${format}.mp4`;
const video = path.join(output, asset);
const storyCard = path.join(arg("cards", "promo-cards"), `${id}-story.png`);
const copyFile = path.join(arg("copy", "promo-copy"), `${id}.md`);
for (const file of [video, storyCard, copyFile]) if (!fs.existsSync(file)) fail(`missing release asset: ${file}`);

const gh = (args, options = {}) => execFileSync("gh", args, { encoding: "utf8", stdio: options.stdio || "pipe" });
const viewRelease = () => {
  const result = spawnSync("gh", ["release", "view", tag, "-R", repo, "--json", "assets"], { encoding: "utf8" });
  if (result.status !== 0) return null;
  try { return JSON.parse(result.stdout); } catch { return null; }
};
let release = viewRelease();
if (!release) {
  const notes = [
    `Automated promotional campaign: ${project.name}`,
    "",
    "Generated by the free GitHub Actions campaign pipeline.",
    "Telegram and YouTube delivery status is recorded as release assets.",
    "",
    buildCampaign(project).telegram,
  ].join("\n");
  gh(["release", "create", tag, "-R", repo, "--target", process.env.GITHUB_SHA || "HEAD", "--prerelease", "--title", `Promo campaign: ${project.name}`, "--notes", notes]);
  release = viewRelease();
  if (!release) fail("release was not visible after creation");
}
const releaseAssets = new Set((release.assets || []).map((item) => item.name));
gh(["release", "upload", tag, "-R", repo, video, storyCard, copyFile, "--clobber"]);

const publishSetting = process.env.PUBLISH || "";
const enabled = publishSetting === "1" || (publishSetting !== "0" && fs.existsSync(path.join(root, "promo", "PUBLISH_ON")));
if (!enabled) {
  console.log("Automatic publishing is disabled by publish=0 or missing promo/PUBLISH_ON; assets remain in the prerelease.");
  process.exit(0);
}
const cronSecret = process.env.CRON_SECRET;
if (!cronSecret) fail("CRON_SECRET is missing; refusing to publish without the site's authorization");
const campaignCopy = buildCampaign(project);
const channel = project.channel === "coins" ? "coins" : "general";
const marker = async (name, payload) => {
  const file = path.join(output, name);
  fs.writeFileSync(file, JSON.stringify({ ...payload, publishedAt: new Date().toISOString(), tag }, null, 2) + "\n");
  gh(["release", "upload", tag, "-R", repo, file, "--clobber"]);
};
const send = async (to, fields) => {
  const params = new URLSearchParams({ tag, asset, to, ...fields });
  const response = await fetch(`${site().replace(/\/$/, "")}/api/cron/promo-publish?${params}`, {
    method: "GET",
    headers: { authorization: `Bearer ${cronSecret}` },
    signal: AbortSignal.timeout(55_000),
  });
  const body = await response.json().catch(() => ({}));
  return { status: response.status, body };
};

const telegramMarker = `published-telegram-${channel}.json`;
if (!releaseAssets.has(telegramMarker)) {
  const result = await send(channel, { caption: campaignCopy.telegram });
  console.log("Telegram delivery:", result.status, JSON.stringify(result.body));
  if (result.status !== 200 || result.body?.ok !== true) fail(`Telegram publish failed: ${result.body?.reason || result.status}`);
  await marker(telegramMarker, { channel, message: result.body });
} else {
  console.log(`Telegram already published to ${channel}; skipping duplicate.`);
}

const youtubeMarker = "published-youtube.json";
if (!releaseAssets.has(youtubeMarker)) {
  const youtubeTitle = campaignCopy.youtubeTitle.slice(0, 80);
  const lang = projectLanguage(project) === "en" ? "en" : "ar";
  const result = await send("youtube", { title: youtubeTitle, lang, caption: campaignCopy.youtubeDescription });
  console.log("YouTube delivery:", result.status, JSON.stringify(result.body));
  if (result.status === 200 && result.body?.ok === true) {
    await marker(youtubeMarker, { channel: "youtube", videoId: result.body.id || null });
  } else {
    // YouTube consent/credentials are separate from Telegram; keep the release and Telegram post
    // successful, but leave no marker so a later manual rerun can retry after setup.
    console.warn(`YouTube upload not completed: ${result.body?.reason || result.status}`);
  }
} else {
  console.log("YouTube already published; skipping duplicate.");
}
