# 6. SHAM 1 - الاصلي من الصفر - T-LDM كاملة
# ------------------------------------------------------------
class Sham1_TLDM(nn.Module):
    def __init__(self, vocab=64000, d_model=1024, layers=12, latent_dim=1024, latent_steps=20, block_size=128):
        super().__init__()
        self.cfg = dict(vocab=vocab, d_model=d_model, layers=layers)
        self.embed = nn.Embedding(vocab, d_model)
        self.reader = nn.ModuleList([MambaBlock(d_model) for _ in range(layers)])
        self.compressor = Compressor(d_model, latent_dim)
        self.thinker = LatentThinker(latent_dim, latent_steps)
        self.writer = DiffusionWriter(latent_dim, vocab, block_size)
        self.draft = nn.Sequential(BitLinear(d_model, 512), nn.SiLU(), BitLinear(512, vocab))
    def forward(self, input_ids):
        x = self.embed(input_ids)
        for layer in self.reader:
            x = x + layer(x)
        h = self.compressor(x)
        h_think, used = self.thinker(h)
        tokens = self.writer.generate_block(h_think)
        return tokens, {"latent_steps_used": used, "compressed_len": h.shape[1]}
    def speculative_generate(self, input_ids):
        # Speculative : مسودة صغيرة تقترح ، الكبير يوافق في تمريرة واحدة - اسرع 2-3x
        draft_logits = self.draft(self.embed(input_ids))
        full_tokens, info = self.forward(input_ids)
        info["draft_shape"] = tuple(draft_logits.shape)
        return full_tokens, info
    def count_params(self):
        return sum(p.numel() for p in self.parameters())

