# 7. SHAM 2 - جسم مانح مجمد + راس T-LDM + LoRA
# درّب 8.5% فقط ، توفير 80% تكلفة تدريب
# ------------------------------------------------------------
class Sham2_TLDM(nn.Module):
    def __init__(self):
        super().__init__()
        self.donor = nn.Linear(1024, 1024)
        for p in self.donor.parameters():
            p.requires_grad = False  # FREEZE DONOR
        self.compressor = Compressor(1024, 1024)
        self.thinker = LatentThinker(1024, 12)
        self.writer = DiffusionWriter(1024, 64000, 128)
        self.lora_A = nn.Parameter(torch.randn(1024, 16) * 0.01)
        self.lora_B = nn.Parameter(torch.zeros(16, 1024))
    def forward(self, x):
        base = self.donor(x)
        delta = (x @ self.lora_A) @ self.lora_B  # Delta_LoRA
        h = self.compressor(base + delta)
        h_think, _ = self.thinker(h)
        return self.writer.generate_block(h_think)

