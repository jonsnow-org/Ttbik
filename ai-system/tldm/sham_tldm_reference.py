# 9. SELF-EVOLUTION : theta_new = theta_old + Delta_LoRA
# كل نجاح -> LoRA ، كل فشل -> درس
# ------------------------------------------------------------
def save_evolution(task, command, result, success: bool):
    rec = {"task": task, "command": command, "result": result[:500], "success": success}
    name = hashlib.md5(task.encode()).hexdigest()[:10]
    folder = "./memory_lora" if success else "./memory_errors"
    os.makedirs(folder, exist_ok=True)
    path = f"{folder}/{name}.json"
    with open(path, "w", encoding="utf-8") as f:
        json.dump(rec, f, ensure_ascii=False, indent=2)
    return f"Saved to {path}"

