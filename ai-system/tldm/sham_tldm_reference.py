def terminal_loop(model, demo=False):
    print(f"=== SHAM T-LDM Terminal ===")
    print("Type a task or command. Type 'exit' to quit.")
    if demo:
        print("\n[Demo] Task: List files")
        res = execute_command("ls -la")
        print(res[:1000])
        print(save_evolution("demo", "ls -la", res, True))
        print("[Demo] Done. Run without --demo for interactive.")
        return
    while True:
        try:
            u = input("\n>> ")
        except:
            break
        if u.strip() in ["exit", "quit"]:
            break
        start = time.time()
        ids = torch.randint(0, 64000, (1, 32))
        try:
            tokens, info = model.speculative_generate(ids)
        except Exception as e:
            info = {"error": str(e)}
        result = execute_command(u)
        print(f"\n[Terminal Result]\n{result[:2000]}")
        success = "BLOCKED" not in result and "ERROR" not in result
        print(save_evolution(u, u, result, success))
        print(f"[Time] {time.time()-start:.2f}s | Latent {info.get('latent_steps_used','N/A')}")

