def train_sham1(steps=5):
    print("[Sham1 Train] From scratch - Full T-LDM")
    model = Sham1_TLDM()
    print(f"Params: {model.count_params()/1e6:.1f}M | FP16 ~{model.count_params()*2/1e9:.2f} GB | BitNet ~{model.count_params()*0.2/1e9:.2f} GB")
    opt = torch.optim.AdamW([p for p in model.parameters() if p.requires_grad], lr=0.0002)
    os.makedirs("./checkpoints/sham1", exist_ok=True)
    for step in range(steps):
        ids = torch.randint(0, 64000, (2, 32))
        tokens, info = model(ids)
        loss = tokens.float().mean() * 0.01 + torch.tensor(0.001)
        opt.zero_grad(); loss.backward(); opt.step()
        print(f"Step {step} loss {loss.item():.4f} latent {info['latent_steps_used']} compressed {info['compressed_len']}")
    torch.save({"model": model.state_dict()}, "./checkpoints/sham1/final.pt")
    print("Saved ./checkpoints/sham1/final.pt")
    return model

