# 8. SAFETY - Sandbox : ممنوع تنفيذ اوامر خطيرة
# ------------------------------------------------------------
FORBIDDEN = ["rm -rf", "sudo", "passwd", "shutdown", "curl", "wget", "chmod 777", "mkfs"]
def is_safe(command: str):
    for f in FORBIDDEN:
        if f in command:
            return False, f"Forbidden: {f}"
    if command.strip().split()[0] in ["rm", "sudo", "su", "chmod", "chown"] if command.strip() else False:
        return False, "Not allowed"
    return True, "OK"

def execute_command(command: str, timeout=10):
    ok, reason = is_safe(command)
    if not ok:
        return f"[BLOCKED] {reason}"
    try:
        r = subprocess.run(command, shell=True, capture_output=True, text=True, timeout=timeout, cwd=os.getcwd())
        out = (r.stdout + r.stderr)[:4000]
        return out if out else "[OK - no output]"
    except subprocess.TimeoutExpired:
        return "[ERROR] Timeout"
    except Exception as e:
        return f"[ERROR] {e}"

