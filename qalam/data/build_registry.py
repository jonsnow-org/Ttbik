"""Builds qalam/data/sources.json: EVERY data source our earlier models used (OneCore's data/sources.yaml in the Lena9 repository, Sham's catalogue and extra sources), classified for Qalam.
Nothing is downloaded. Each entry says where it came from, its domain, and what must happen before training: `ready_check_license` (a public corpus: verify the licence, then admit),
`owner_review` (generated by other models: the owner's rule is no commercial-model outputs, so these wait for a decision), or `media_later` (for the codec notebooks N13-N19).
Usage: python build_registry.py LENA9_ROOT SHAM_CATALOG_JSON SHAM_EXTRA_SOURCES_PY OUT_JSON"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import yaml

# What can be said with certainty about a licence without opening the dataset card; everything else is "verify".
KNOWN = {"wikimedia/wikipedia": "CC BY-SA 3.0 / GFDL (share-alike: keep attribution)", "HuggingFaceFW/fineweb-2": "ODC-By 1.0 + Common Crawl terms",
         "HuggingFaceFW/fineweb-edu": "ODC-By 1.0 + Common Crawl terms", "epfml/FineWeb2-HQ-Plus": "verify (derived from FineWeb-2)"}
# Datasets whose text was WRITTEN BY OTHER MODELS (distillation / synthetic chat): the owner's rule decides, not me.
GENERATED = {"teknium/OpenHermes-2.5", "2A2I/Arabic-OpenHermes-2.5", "HuggingFaceH4/ultrachat_200k", "open-r1/OpenR1-Math-220k", "open-r1/Mixture-of-Thoughts",
             "CohereLabs/tiny-aya-l2-thinker-multilingual-reasoning", "HuggingFaceTB/cosmopedia", "Saxo/alpaca_function_calling_dataset", "ShareGPT4V", "ShareGPT4Video"}
MEDIA = ("fleurs", "common_voice", "gigaspeech", "arabic_speech", "wavcaps", "open_images", "sard", "flickr", "coyo", "cc12m", "conceptual", "sharegpt4", "msr", "webvid", "hd_vila",
         "youcook", "finevideo", "bvd", "internvid", "panda", "gigaspeechbench", "arvoice", "clartts", "cc3m", "coco", "hdvila", "openimages", "videos4")


def domain_of(sid: str, repo: str, config: str) -> str:
    s = (sid + " " + repo).lower()
    if any(m in s for m in MEDIA):
        return "media"
    if "stack" in s or "code" in s:
        return "code"
    if any(k in s for k in ("math", "proof")):
        return "math"
    if any(k in s for k in ("function_calling", "tool")):
        return "tools"
    ar = re.search(r"(_ar\b|arab|\bar_|arz|ars|ary|acm|arq|jais|aya|eou|cluster)", s + " " + config.lower())
    return "arabic" if ar else "english" if re.search(r"(_en\b|eng_|english|smollm|fineweb_edu|fineweb-edu|c4|oscar)", s) else "multilingual"


def status_of(repo: str, sid: str, domain: str) -> tuple[str, str]:
    if domain == "media":
        return "media_later", "for the media codec notebooks (N13-N19), after the text model's architecture is frozen"
    if repo in GENERATED or any(g.lower() in sid.lower() for g in ("hermes", "ultrachat", "openr1", "mixture_of_thoughts", "tiny_aya", "teacher_qa", "cosmopedia", "saxo", "sharegpt4")):
        return "owner_review", "text written by other models: needs the owner's decision under the no-commercial-model-outputs rule"
    return "ready_check_license", "public corpus: verify the licence on its dataset card, then admit through data.admit"


def main() -> None:
    lena, catalog, extra, out = sys.argv[1:5]
    entries: dict[str, dict] = {}

    def add(sid, repo, config, origin, **kw):
        key = f"{repo}|{config}"
        dom = domain_of(sid, repo, config)
        st, why = status_of(repo, sid, dom)
        e = entries.setdefault(key, {"id": sid, "repo": repo, "config": config, "domain": dom, "origin": [], "license": KNOWN.get(repo, "verify"), "status": st, "why": why})
        if origin not in e["origin"]:
            e["origin"].append(origin)
        e.update({k: v for k, v in kw.items() if v is not None})

    y = yaml.safe_load((Path(lena) / "onecore-ai/data/sources.yaml").read_text(encoding="utf-8"))
    for s in y["sources"]:
        add(s["id"], s["repo"], s.get("config", ""), "onecore", onecore_enabled=bool(s.get("enabled", True)), onecore_train_limit=(s.get("limits") or {}).get("train"))
    for s in json.loads(Path(catalog).read_text(encoding="utf-8"))["sources"]:
        add(s["id"], s["repo"], s.get("config", ""), "sham")
    junk = {"a/train", "b/train", "source/split", "train/part_N", "val/part_N"}                   # path-like strings in the sources' code, not repositories
    for repo in sorted(set(re.findall(r'"([A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+)"', Path(extra).read_text(encoding="utf-8"))) - junk):
        add(repo.split("/")[-1], repo, "", "sham")
    reg = sorted(entries.values(), key=lambda e: (e["status"], e["domain"], e["id"]))
    summary: dict = {}
    for e in reg:
        summary.setdefault(e["status"], {}).setdefault(e["domain"], 0)
        summary[e["status"]][e["domain"]] += 1
    Path(out).write_text(json.dumps({"built": "2026-11-28", "note": "no data downloaded; licences marked 'verify' are unverified", "summary": summary, "sources": reg}, indent=1, ensure_ascii=False), encoding="utf-8")
    print(json.dumps(summary, ensure_ascii=False))


if __name__ == "__main__":
    main()
