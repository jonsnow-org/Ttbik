// One short, uniform /start message for every bot template: what the bot is,
// how it works, what is inside. Text only — keyboards and flows stay in each
// bot's own logic file.

type Guide = { emoji: string; name: string; what: string; steps: string[]; contents: string[] };

const NUM = ["1️⃣", "2️⃣", "3️⃣", "4️⃣"];

function render(g: Guide): string {
  return (
    `${g.emoji} أهلاً بك في «${g.name}»\n${g.what}\n\n` +
    `⚙️ كيف يعمل؟\n${g.steps.map((s, i) => `${NUM[i]} ${s}`).join("\n")}\n\n` +
    `📂 المحتويات\n${g.contents.join(" · ")}\n\n` +
    `ℹ️ للمزيد اضغط «معلومات».`
  );
}

