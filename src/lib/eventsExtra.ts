export function isEventCurrent(event: Pick<EventItem, "dateIso" | "endDateIso">, today: string): boolean {
  return event.dateIso <= today && (event.endDateIso ?? event.dateIso) >= today;
}

export function isEventUpcomingOrCurrent(event: Pick<EventItem, "dateIso" | "endDateIso">, today: string): boolean {
  return event.dateIso > today || isEventCurrent(event, today);
}

